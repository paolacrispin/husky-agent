/**
 * Logo lines for a style and width. Falls back to the closest available
 * width at or below the request, so a user-configurable width can never
 * blow up your layout.
 */
export function huskyLogo(
  style: HuskyLogoStyle = "blocks",
  width = 25,
): string[] {
  const byWidth = HUSKY_LOGO[style];
  const available = HUSKY_LOGO_WIDTHS[style];
  if (!available.length) return [];
  const pick = available.includes(width)
    ? width
    : available.filter((w) => w <= width).pop() ?? available[0];
  return byWidth[pick];
}

export const HUSKY_DEFAULT_STYLE: HuskyLogoStyle = "blocks";
export const HUSKY_DEFAULT_WIDTH = 25;

/** Drop-in splash logo: the recommended style at the largest width. */
export const HUSKY_LOGO_LINES: string[] = huskyLogo(
  HUSKY_DEFAULT_STYLE,
  HUSKY_DEFAULT_WIDTH,
);
